// api/ads.js - Vercel serverless function
// Paid ads & social platform foundation (Meta, Google Ads, TikTok).
// Step 1 of the paid-ads-social build: the connection framework. Mirrors
// the Phase 15 Universal Connections flow in api/marketing.js exactly (see
// api/_lib/connection-states.js), applied to the new ad_platform_connections
// table (sql/058) instead of marketing_platform_connections -- ad
// platforms need their own row shape (business_account_id, ad_account_id,
// env_var_name) but the same connect -> verify-reporting -> verify-draft
// -> enable-launch sequence and issue-state vocabulary.
//
// Usage:
//   GET  /api/ads?resource=ad_connections
//     -> current state of all 3 ad platforms, real rows from
//        ad_platform_connections (not_connected if no row exists yet).
//   POST /api/ads?resource=ad_connection_transition
//     body: { platform, toState, note?, envVarName? }
//     -> moves one platform's connection to a new state, enforcing the
//        same legal-transition rules as marketing_platform_connections.
//
//   GET  /api/ads?resource=ad_campaigns[&platform=][&status=]
//     -> real ad_campaigns rows, optionally filtered.
//   POST /api/ads?resource=ad_campaign_draft
//     body: { platform, objective, division, dailyBudgetCents, adCopy? }
//     -> creates a draft ad_campaigns row. adCopy is optional -- if
//        omitted, ad copy is generated by AI, grounded only in real
//        division job facts + service territory facts (never fabricated),
//        and refuses honestly (409) if ANTHROPIC_API_KEY is not set.
//   POST /api/ads?resource=ad_campaign_review
//     body: { campaignId, decision: 'approve'|'reject', reason? }
//     -> approve moves draft -> pending_review, but only after a real
//        budget-headroom check (api/_lib/ad-budget-governor.js) passes;
//        reject moves draft -> rejected with a stored reason. Neither
//        touches a real platform -- that is still step 3.
//
//   POST /api/ads?resource=ad_campaign_launch
//     body: { campaignId, linkUrl? }
//     -> the first real platform action in this build: launches an
//        approved (pending_review) campaign for real. Meta goes through
//        the Graph API (api/_lib/ad-platform-meta.js); Google Ads goes
//        through the Google Ads REST API (api/_lib/ad-platform-google.js).
//        Requires that platform's connection to already be launch_enabled
//        and its real credentials to be present as Vercel project
//        settings, and re-checks budget headroom before calling out. On
//        success moves the campaign to active with its real
//        external_campaign_id; on failure records the classified
//        connection issue state (needs_reauth/policy_blocked/
//        billing_blocked/needs_attention) and leaves the campaign in
//        pending_review for a retry once fixed.
//
//   POST /api/ads?resource=ad_campaign_pause
//     body: { campaignId, reason? }
//     -- pauses a real, currently active Meta or Google Ads campaign. Only
//        an active campaign can be paused. A failure is classified and
//        recorded on the connection exactly like a launch failure -- never
//        swallowed.
//
//   POST /api/ads?resource=ad_spend_sync
//     body: { campaignId, date? }  (date defaults to today, UTC, YYYY-MM-DD)
//     -- pulls that day's real reported spend for a launched Meta or
//        Google Ads campaign from that platform's own reporting endpoint
//        and upserts it into ad_spend_ledger (the same table the budget
//        governor sums against the cap). Never estimates or invents a
//        number -- only ever writes what the platform itself reports.
//
// Meta, Google Ads, and TikTok are all wired up for a real
// launch/pause/spend-sync now (steps 3 + 5, all three ad platforms this
// build was scoped for). None of the three launch codepaths have ever been
// exercised against a real ad account -- see the header of each
// api/_lib/ad-platform-*.js file. Organic social posting (step 6) is a
// separate subsystem in api/social-posts.js, not this file.
//
// Google Ads credential shape: ad_platform_connections.env_var_name for
// platform='google_ads' must point to a Vercel env var whose value is a
// JSON blob {"developerToken":"...","clientId":"...","clientSecret":"...",
// "refreshToken":"..."} -- see the header of api/_lib/ad-platform-google.js
// for why (Google Ads needs four secrets, not one token like Meta).
// ad_platform_connections.ad_account_id is the Google Ads Customer ID;
// business_account_id is the optional MCC (manager account) id.
//
// TikTok credential shape matches Meta's -- a single long-lived access
// token in the named env var, ad_account_id reused as the TikTok Advertiser
// ID. See the header of api/_lib/ad-platform-tiktok.js for TikTok's honest
// limitation: real ads require a real uploaded video/image asset id, which
// this build has no upload pipeline for yet -- launch refuses rather than
// fabricating creative when ad_copy has no mediaAssetId.

